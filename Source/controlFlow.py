# If only cond1 and cond2 are true else false
age = 17
citizenShip = ""
if age >= 18 and citizenShip:
    print("Age is greater than or equal to 18 and citizenShip is true")
else:
    print("Age is less than or equal to 18 and citizenShip is false")

#OR
age = 17
permissions = True
if age >= 18 or permissions:
    print("go to movie")
else:
    print("Not going anywheres")

#Not
